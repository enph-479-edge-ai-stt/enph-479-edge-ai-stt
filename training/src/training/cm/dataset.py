"""LM text -> one EOS-separated stream of vocab indices.

Follows the paper: the char-LM trains on "a text stream generated by concatenating
randomly selected sentences ... where the EOS label is inserted between the
sentences". The stream is a ``uint8`` numpy array (one byte per character), so a
few hundred million characters fit in memory and on the GPU.
"""

from __future__ import annotations

import gzip
import random
from pathlib import Path

import numpy as np

from training import vocab

# Byte -> vocab index. Newline stands in for EOS while joining; 255 marks out-of-vocab.
_OOV = 255
_LUT = np.full(256, _OOV, dtype=np.uint8)
for _i, _c in enumerate(vocab.CHARS):
    if len(_c) == 1:
        _LUT[ord(_c)] = _i
_LUT[ord("\n")] = vocab.EOS_IDX


def sample_sentences(gz_path: str | Path, keep: float, seed: int = 0) -> list[str]:
    """Stream a gzipped one-sentence-per-line corpus and keep a random ``keep`` fraction.

    The kept sentences come back shuffled, so the stream doesn't follow book order.
    """
    rng = random.Random(seed)
    with gzip.open(gz_path, "rt", encoding="utf-8") as f:
        kept = [line.rstrip("\n") for line in f if rng.random() < keep]
    rng.shuffle(kept)
    return kept


def to_stream(sentences: list[str]) -> np.ndarray:
    """Join sentences as ``EOS s1 EOS s2 ... EOS`` and encode to ``uint8`` vocab indices.

    Raises ``ValueError`` if any character is outside the vocab.
    """
    text = "\n" + "\n".join(sentences) + "\n"
    stream = _LUT[np.frombuffer(text.encode("utf-8"), dtype=np.uint8)]
    if (stream == _OOV).any():
        bad = sorted({c for c in text if c != "\n" and c not in vocab.CHARS})
        raise ValueError(f"out-of-vocab characters in LM text: {bad}")
    return stream
